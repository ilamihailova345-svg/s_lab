package main

import (
	"fmt"
	"sync"
)

func main() {
	// счётчик активных горутин
	var wg sync.WaitGroup

	// запускаем 3 горутины
	for i := 1; i <= 3; i++ {
		// перед запуском горутины увеличиваем счётчик на 1
		wg.Add(1)

		// передаём i как аргумент, чтобы избежать проблемы замыкания
		go func(id int) {
			// гарантирует, что счётчик уменьшится
			defer wg.Done()

			switch id {
			case 1:
				fmt.Println("Горутина 1: Привет!")
			case 2:
				fmt.Println("Горутина 2: Мир!")
			case 3:
				fmt.Println("Горутина 3: Golang!")
			}
		}(i)
	}

	// блокирует main, пока счётчик не станет 0
	// ждём, пока все 3 горутины вызовут wg.Done()
	// без этого main завершится сразу после цикла, и горутины не успеют вывести
	wg.Wait()
}